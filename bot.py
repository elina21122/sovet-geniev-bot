# Хранилище истории диалогов: {user_id: [{"role": ..., "content": ...}]}
user_histories = {}
MAX_HISTORY = 20  # максимум сообщений в истории на пользователя


async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    user_id = update.effective_user.id
    user_histories[user_id] = []
    await update.message.reply_text(
        "Совет гениев собрался.\n\n"
        "Задайте ваш стратегический вопрос — и шесть разных умов разберут его со всех сторон.\n\n"
        "Команды:\n"
        "/start — начать новую сессию\n"
        "/reset — сбросить историю диалога"
    )


async def reset(update: Update, context: ContextTypes.DEFAULT_TYPE):
    user_id = update.effective_user.id
    user_histories[user_id] = []
    await update.message.reply_text("История сброшена. Начинаем новое заседание.")


async def handle_message(update: Update, context: ContextTypes.DEFAULT_TYPE):
    user_id = update.effective_user.id
    user_text = update.message.text

    # Инициализируем историю если нет
    if user_id not in user_histories:
        user_histories[user_id] = []

    # Добавляем сообщение пользователя в историю
    user_histories[user_id].append({"role": "user", "content": user_text})

    # Обрезаем историю если слишком длинная
    if len(user_histories[user_id]) > MAX_HISTORY:
        user_histories[user_id] = user_histories[user_id][-MAX_HISTORY:]

    # Отправляем индикатор печати
    await context.bot.send_chat_action(chat_id=update.effective_chat.id, action="typing")

    try:
        response = client.chat.completions.create(
            model="gpt-4o",
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                *user_histories[user_id]
            ],
            max_tokens=3000,
            temperature=0.85,
        )

        assistant_message = response.choices[0].message.content

        # Добавляем ответ в историю
        user_histories[user_id].append({"role": "assistant", "content": assistant_message})

        # Разбиваем по смысловым блокам
        import re
        sections = re.split(r'\n(?=ВОПРОС НА РАССМОТРЕНИЕ:|ОТКРЫТИЕ:|ВИЗИОНЕР:|ИНВЕСТОР:|ПЕРФЕКЦИОНИСТ:|АНАЛИТИК:|КЛИЕНТ:|СТРАТЕГ:|СИНТЕЗ:|СВОДНАЯ ТАБЛИЦА:)', assistant_message)
        blocks = []
        current = ""
        for section in sections:
            if len(current) + len(section) + 1 > 4096:
                if current:
                    blocks.append(current.strip())
                current = section
            else:
                current = (current + "\n" + section) if current else section
        if current:
            blocks.append(current.strip())

        for block in blocks:
            await update.message.reply_text(block)

    except Exception as e:
        logger.error(f"Ошибка OpenAI: {e}")
        await update.message.reply_text("Совет временно недоступен. Попробуйте через минуту.")


def main():
    app = Application.builder().token(TELEGRAM_TOKEN).build()
    app.add_handler(CommandHandler("start", start))
    app.add_handler(CommandHandler("reset", reset))
    app.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND, handle_message))
    logger.info("Бот запущен")
    app.run_polling()


if __name__ == "__main__":
    main()
